  /// Helper to aggregate all characters into a single combined list, tagged
  /// with the same category titles used by CategoryScreen/StickerService so
  /// unlock keys ("Category:Name") can be reconstructed from a character map.
  static List<Map<String, String>> getAllCharacters() {
    final sections = <String, List<Map<String, String>>>{
      'Cars': getCars(),
      'Madagascar': getMadagascar(),
      'Minions': getMinions(),
      'Toy Story': getToyStory(),
      'Monsters Inc': getMonstersInc(),
      'Superheroes': getSuperheroes(),
      'Super Mario': getSuperMario(),
      'Paw Patrol': getPawPatrol(),
      'Zootopia': getZootopia(),
      'Pokemon': getPokemonCharacters(),
    };

    return [
      for (final entry in sections.entries)
        for (final character in entry.value)
          {...character, 'category': entry.key},
    ];
  }
